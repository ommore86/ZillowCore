import uuid
from typing import List, Optional
from datetime import datetime
from fastapi import APIRouter, Depends, HTTPException
from sqlalchemy.orm import Session
from app.core.database import get_db
from app.core.middleware import get_current_user, log_audit_trail
from app.models.models import User, MaintenanceTicket, WorkOrder, Property, Vendor
from app.schemas.schemas import (
    MaintenanceTicketCreate, MaintenanceTicketResponse,
    WorkOrderCreate, WorkOrderResponse
)
from app.services.ai.orchestrator import MultiAgentOrchestrator

router = APIRouter(prefix="/maintenance", tags=["Maintenance & Facility Management"])

@router.get("/tickets", response_model=List[MaintenanceTicketResponse])
def list_tickets(
    status: Optional[str] = None,
    priority: Optional[str] = None,
    current_user: User = Depends(get_current_user),
    db: Session = Depends(get_db)
):
    q = db.query(MaintenanceTicket).filter(MaintenanceTicket.org_id == current_user.org_id)
    if status:
        q = q.filter(MaintenanceTicket.status == status)
    if priority:
        q = q.filter(MaintenanceTicket.priority == priority)
    return q.order_by(MaintenanceTicket.created_at.desc()).all()

@router.post("/tickets", response_model=MaintenanceTicketResponse)
def create_ticket(
    payload: MaintenanceTicketCreate,
    current_user: User = Depends(get_current_user),
    db: Session = Depends(get_db)
):
    prop = db.query(Property).filter(Property.id == payload.property_id, Property.org_id == current_user.org_id).first()
    if not prop:
        raise HTTPException(status_code=404, detail="Property not found")

    # Run AI Maintenance Triage Agent for intelligent classification & SLA
    triage_result = MultiAgentOrchestrator._run_maintenance_triage(
        db, current_user.org_id,
        {"title": payload.title, "description": payload.description}
    )

    ticket = MaintenanceTicket(
        org_id=current_user.org_id,
        property_id=payload.property_id,
        unit_id=payload.unit_id,
        requester_contact_id=payload.requester_contact_id,
        title=payload.title,
        description=payload.description,
        category=triage_result["triaged_category"],
        priority=triage_result["assigned_priority"],
        sla_hours=triage_result["target_sla_hours"],
        assigned_vendor_id=triage_result["recommended_vendor"]["id"],
        status="open",
        estimated_cost=3500.0
    )
    db.add(ticket)
    db.flush()

    # Automatically generate Work Order if high/urgent priority
    if ticket.priority in ("high", "urgent"):
        work_order = WorkOrder(
            org_id=current_user.org_id,
            ticket_id=ticket.id,
            vendor_id=ticket.assigned_vendor_id,
            work_order_number=f"WO-{datetime.utcnow().strftime('%Y%m')}-{uuid.uuid4().hex[:6].upper()}",
            status="issued",
            total_cost=ticket.estimated_cost,
            notes=f"Auto-generated by Maintenance Triage Agent ({ticket.category.upper()})"
        )
        db.add(work_order)

    log_audit_trail(db, current_user.org_id, "create", "maintenance_ticket", ticket.id, user_id=current_user.id)
    db.commit()
    db.refresh(ticket)
    return ticket

@router.get("/tickets/{id}", response_model=MaintenanceTicketResponse)
def get_ticket(
    id: str,
    current_user: User = Depends(get_current_user),
    db: Session = Depends(get_db)
):
    ticket = db.query(MaintenanceTicket).filter(MaintenanceTicket.id == id, MaintenanceTicket.org_id == current_user.org_id).first()
    if not ticket:
        raise HTTPException(status_code=404, detail="Ticket not found")
    return ticket

@router.put("/tickets/{id}/status")
def update_ticket_status(
    id: str,
    status: str,
    current_user: User = Depends(get_current_user),
    db: Session = Depends(get_db)
):
    ticket = db.query(MaintenanceTicket).filter(MaintenanceTicket.id == id, MaintenanceTicket.org_id == current_user.org_id).first()
    if not ticket:
        raise HTTPException(status_code=404, detail="Ticket not found")

    ticket.status = status
    if status in ("resolved", "closed"):
        ticket.resolved_at = datetime.utcnow()

    log_audit_trail(db, current_user.org_id, "update_status", "maintenance_ticket", ticket.id, user_id=current_user.id)
    db.commit()
    return {"message": f"Ticket status updated to {status}", "ticket_id": id}

# Work Orders
@router.get("/work-orders", response_model=List[WorkOrderResponse])
def list_work_orders(
    current_user: User = Depends(get_current_user),
    db: Session = Depends(get_db)
):
    return db.query(WorkOrder).filter(WorkOrder.org_id == current_user.org_id).all()

@router.post("/work-orders", response_model=WorkOrderResponse)
def create_work_order(
    payload: WorkOrderCreate,
    current_user: User = Depends(get_current_user),
    db: Session = Depends(get_db)
):
    wo = WorkOrder(
        org_id=current_user.org_id,
        ticket_id=payload.ticket_id,
        vendor_id=payload.vendor_id,
        work_order_number=payload.work_order_number,
        scheduled_date=payload.scheduled_date,
        total_cost=payload.total_cost,
        notes=payload.notes,
        status="issued"
    )
    db.add(wo)
    db.commit()
    db.refresh(wo)
    return wo

